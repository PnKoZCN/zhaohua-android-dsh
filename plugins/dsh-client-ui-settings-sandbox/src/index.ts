/**
 * ZhaoHua sandbox settings page, node half: owns the `/api/zhbox` HTTP route
 * (status / toggle / install / test) that drives the local proot sandbox. The
 * browser half owns the settings page through exports["./client"].
 *
 * Every route sits behind the connection trust fence (the same rejection the
 * other host routes use): an unauthenticated request is dropped before any
 * command runs.
 */
import { execFile } from 'node:child_process'
import { readFile, writeFile, mkdir, copyFile, chmod } from 'node:fs/promises'
import path from 'node:path'
import { ZH_SETUP_B64 } from './zh-setup-b64.js'

/** Cordis function-plugin name. */
export const name = 'zhbox'

/** The route carrier and the trust fence guarding it. */
export const inject = ['webServer', 'connection']

type IncomingMessage = import('node:http').IncomingMessage
type ServerResponse = import('node:http').ServerResponse
interface WebServerLike {
  register(route: unknown, label?: string): unknown
}
interface ConnectionLike {
  requestRejection(req: IncomingMessage): number | undefined
}
interface Ctx {
  webServer: WebServerLike
  connection: ConnectionLike
}

const statePath = (): string => path.join(process.env.DSH_HOME ?? process.cwd(), 'zhaohua-sandbox.state')
const sandboxDir = (): string => path.join(process.env.DSH_HOME ?? process.cwd(), 'zh-sandbox')
/**
 * The payload root: this module lives at
 * <payload>/dshroot/lib/node_modules/@deepseek-ai/dsh/node_modules/@zhaohua/dsh-client-ui-settings-sandbox/lib/index.js
 * — nine levels up from lib/. process.cwd() is NOT the payload (the engine's
 * cwd is the harness home), so the module URL is the only reliable anchor.
 */
const payloadDir = (): string => path.resolve(process.env.DSH_HOME ?? process.cwd(), '..')
const payloadBin = (): string => path.join(payloadDir(), 'bin')
const filesDir = (): string => process.env.DSH_HOME ?? payloadDir()

function run(file: string, args: readonly string[], timeoutMs: number): Promise<{ code: number, stdout: string, stderr: string }> {
  return new Promise((resolve) => {
    execFile(file, [...args], { timeout: timeoutMs, maxBuffer: 4 << 20, encoding: 'utf8' }, (error, stdout, stderr) => {
      const code = (error as unknown as { code?: unknown })?.code
      resolve({ code: typeof code === 'number' ? code : (error ? 1 : 0), stdout: String(stdout ?? ''), stderr: String(stderr ?? '') })
    })
  })
}

async function status(): Promise<Record<string, unknown>> {
  let toggle = 'off'
  try { toggle = (await readFile(statePath(), 'utf8')).trim().toLowerCase() === 'on' ? 'on' : 'off' } catch {}
  let rootfs = false
  try { await readFile(path.join(sandboxDir(), 'rootfs/usr/bin/zh-setup')); rootfs = true } catch {}
  const probe = await run(path.join(payloadBin(), 'proot'), ['--version'], 8000)
  return {
    toggle,
    rootfsReady: rootfs,
    prootVersion: probe.code === 0 ? probe.stdout.split('\n')[0] : `unavailable: ${(probe.stderr.split('\n')[0] ?? '').trim()}`,
  }
}

async function testSandbox(): Promise<Record<string, unknown>> {
  const zhbox = await ensureZhbox()
  const r = await run('sh', [zhbox, '/bin/bash', '-c', 'id -u; cat /etc/alpine-release 2>/dev/null; gcc --version 2>/dev/null | head -1; python3 -V 2>/dev/null; node -v 2>/dev/null'], 60000)
  return { code: r.code, output: `${r.stdout}${r.stderr}`.trim() }
}

/** Write the embedded installer to DSH_HOME so the sandbox can run it. */
async function ensureSetupScript(): Promise<string> {
  const target = path.join(filesDir(), 'zh-setup-runtime.sh')
  await writeFile(target, Buffer.from(ZH_SETUP_B64, 'base64'))
  await chmod(target, 0o755).catch(() => {})
  return target
}

/** Host-side helper to run one command inside the sandbox (mirrors the router). */
async function ensureZhbox(): Promise<string> {
  const sbx = sandboxDir()
  const zhbox = path.join(sbx, 'zhbox.sh')
  const files = filesDir()
  const script = `#!/system/bin/sh
# ZhaoHua sandbox runner (generated by the zhbox settings plugin).
PAYLOAD=${JSON.stringify(payloadDir())}
S=${JSON.stringify(sbx)}
FILES=${JSON.stringify(files)}
export LD_LIBRARY_PATH="$PAYLOAD/bin"
export PROOT_LOADER="$PAYLOAD/bin/proot-loader"
export PROOT_TMP_DIR="$S/tmp"
exec timeout 1800 "$PAYLOAD/bin/proot" \
  -r "$S/rootfs" -0 -w /root --link2symlink --kill-on-exit \
  -b /dev -b /proc -b /sys -b /sdcard \
  -b "$FILES":"$FILES" \
  -b "$S/tmp":"/tmp" \
  /usr/bin/env -i TERM=xterm HOME=/root \
  PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin \
  PROOT_TMP_DIR="$S/tmp" TMPDIR=/tmp \
  "$@"
`
  await mkdir(sbx, { recursive: true })
  await writeFile(zhbox, script)
  await chmod(zhbox, 0o755).catch(() => {})
  return zhbox
}

async function readBody(req: IncomingMessage): Promise<string> {
  return new Promise((resolve) => {
    let body = ''
    req.on('data', (chunk: Buffer) => { body += String(chunk) })
    req.on('end', () => resolve(body))
    req.on('error', () => resolve(body))
  })
}

async function handle(ctx: Ctx, req: IncomingMessage, res: ServerResponse): Promise<void> {
  const send = (code: number, body: unknown): void => {
    res.statusCode = code
    res.setHeader('content-type', 'application/json')
    res.end(JSON.stringify(body))
  }
  const url = new URL(String(req.url), 'http://localhost')
  const action = url.pathname.replace('/api/zhbox', '').replace(/^\//, '') || 'status'
  try {
    if (req.method === 'GET' && action === 'status') return send(200, await status())
    if (req.method === 'POST' && action === 'toggle') {
      const current = await status()
      const next = current.toggle === 'on' ? 'off' : 'on'
      await writeFile(statePath(), `${next}\n`)
      return send(200, { toggle: next })
    }
    if (req.method === 'POST' && action === 'install') {
      const sbx = sandboxDir()
      await mkdir(path.join(sbx, 'rootfs'), { recursive: true })
      await mkdir(path.join(sbx, 'tmp'), { recursive: true })
      let seeded = false
      try { await readFile(path.join(sbx, 'rootfs/usr/bin/zh-setup')); seeded = true } catch {}
      if (!seeded) {
        const tar = path.join(filesDir(), 'zh-rootfs.tar.gz')
        const x = await run('tar', ['xzf', tar, '-C', path.join(sbx, 'rootfs')], 300000)
        if (x.code !== 0) return send(500, { error: `rootfs extract failed: ${x.stderr.slice(0, 400)}` })
      }
      // Seed the in-sandbox toolbox installer + exec bits + resolver (the
      // shipped rootfs and binaries may lack them; idempotent self-heal).
      await chmod(path.join(payloadBin(), 'proot'), 0o755).catch(() => {})
      await chmod(path.join(payloadBin(), 'proot-loader'), 0o755).catch(() => {})
      const resolv = path.join(sbx, 'rootfs/etc/resolv.conf')
      await writeFile(resolv, 'nameserver 1.1.1.1\nnameserver 8.8.8.8\n').catch(() => {})
      const zhbox = await ensureZhbox()
      // Run the HOST copy of zh-setup: dshhome is bind-mounted into the
      // sandbox at its host path, so the freshest installer always runs and
      // the in-rootfs copy (possibly stale from an older payload) is moot.
      // internal-patch extraction does not preserve exec bits, so chmod first
      // and invoke through `sh` anyway (reads the file, exec bit moot).
      const setupScript = await ensureSetupScript()
      const install = await run('sh', [zhbox, 'sh', setupScript], 600000)
      return send(200, { code: install.code, output: `${install.stdout}${install.stderr}`.trim().slice(-4000) })
    }
    if (req.method === 'POST' && action === 'gorust') {
      const sbx = sandboxDir()
      await mkdir(path.join(sbx, 'rootfs'), { recursive: true })
      await mkdir(path.join(sbx, 'tmp'), { recursive: true })
      const zhbox = await ensureZhbox()
      const setupScript = await ensureSetupScript()
      const install = await run('sh', [zhbox, 'sh', setupScript, '--only=gorust'], 600000)
      return send(200, { code: install.code, output: `${install.stdout}${install.stderr}`.trim().slice(-4000) })
    }
    if (req.method === 'POST' && action === 'test') return send(200, await testSandbox())
    return send(404, { error: `unknown action: ${action}` })
  } catch (error) {
    return send(500, { error: error instanceof Error ? error.message : String(error) })
  }
}

/** Register the zhbox routes behind the connection trust fence. */
export function apply(ctx: Ctx): void {
  const rejected = (req: IncomingMessage, res: ServerResponse): boolean => {
    const rejection = ctx.connection.requestRejection(req)
    if (rejection === undefined) return false
    res.statusCode = rejection
    res.end()
    return true
  }
  ctx.webServer.register({
    kind: 'prefix',
    path: '/api/zhbox',
    handler: async (req: IncomingMessage, res: ServerResponse) => {
      if (rejected(req, res)) return
      if (req.method === 'POST' && ['toggle', 'install', 'test', 'gorust'].includes(new URL(String(req.url), 'http://localhost').pathname.replace('/api/zhbox', '').replace(/^\//, ''))) {
        // Body is not consumed by these actions; drain defensively.
        await readBody(req)
      }
      await handle(ctx, req, res)
    },
  }, 'zhbox: sandbox control route')
}
